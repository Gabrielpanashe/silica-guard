"""v2 content store: every patient-facing string as reviewed, versioned data

Revision ID: 0006_v2_content
Revises: 0005_v2_instrument
Create Date: 2026-11-01

Master Reference v1.0 §8.4, and the channel budgets in §13.1-13.2. The fourth
of the five irreversible decisions: **no runtime machine translation of
anything a worker reads or hears, and no model-generated free text on any
patient-facing surface.** Two tables, additive only -- nothing existing is
touched.

`messages` is the versioned unit and carries the review state; `message_texts`
holds the words, one row per language. A new language is rows in the second
table and nothing else, which is the property the whole design exists for:
English, Shona and Ndebele from the start, with Ndebele not optional in this
geography.

Why `status` sits on `messages` rather than on each language row, departing
from the sketch in docs/IMPLEMENTATION_PLAN.md §4: the reviewable source file
carries one status per message and `content/schema.json` requires all three
languages before that status may be `approved`. Splitting approval per
language would let a message be half-approved and therefore sendable to some
workers and not others, which is a worse failure than waiting for the third
translation. The file format, the validator, these tables and
`services/content_store.py` now agree on one lifecycle.

Why `message_texts.septets` is stored rather than computed on read: it is the
GSM 03.38 cost that `services/content_format.py` computed at load time, and
storing it makes the segment arithmetic auditable instead of recomputed,
possibly differently, by each caller. A string outside the seven-bit alphabet
never reaches the table at all -- the loader rejects it, because one such
character drops a segment from 160 characters to 70 and permanently multiplies
the cost of every send containing it.

Data only arrives through a later migration generated from `content/`, on a
pull request the Clinical Lead approves (§11.4). This one creates empty
tables, and `content_store.render()` will not serve a message no one has
approved -- so until that happens the store holds nothing a worker can be
shown, which is the correct state rather than a gap.
"""
