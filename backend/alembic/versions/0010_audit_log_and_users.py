"""Users, roles, and the append-only audit log

Revision ID: 0010_audit_log_and_users
Revises: 0009_v2_referrals
Create Date: 2026-11-01

Master Reference v1.0 §16.3 and §16.6. Two tables, additive only.

Two flat accounts from environment variables is the whole access model today
(`routers/auth.py`), and it gates only whether an authenticated route answers
at all. §16.3 names eight roles, each with an explicit "cannot see" column,
and §16.6 puts this in Phase One — before the first real record, because
retrofitting authorisation onto a system that has already been read is how a
breach gets discovered after the fact.

`users` carries scope columns beside the role, because "facility user: can see
referrals directed to their facility" is not a role, it is a role plus a
facility, and without the second half the first is unenforceable. A user is
deactivated rather than deleted: an audit row names a user id, and a deleted
user makes every row referencing it unreadable.

`audit_log` is the half that matters most and the easier half to skip.
§16.3's "administrative access is not a licence to read records; every read
audited" is only true if the read actually writes a row, and a log that can be
edited afterwards answers nothing. It is **append-only**: there is no update
and no delete anywhere in `services/audit.py`, and a test asserts that by
inspecting the module. Enforcement is in the service layer rather than a
database trigger for the fourth time in this schema, because triggers are
PostgreSQL-only and invisible to the SQLite unit suite (§16.2).

`audit_log.allowed` records refusals as well as successes, and the refusals
are the rows that matter: a role boundary nobody can show being enforced is a
role boundary nobody can show exists.

`actor_email` and `actor_role` are denormalised beside `actor_user_id`
deliberately. A log that becomes unreadable when a user row changes or is
deactivated is not a log.
"""
