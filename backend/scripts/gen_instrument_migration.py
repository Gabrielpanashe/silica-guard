"""Generate the data migration that loads one instrument version.

    ./venv/Scripts/python.exe scripts/gen_instrument_migration.py \
        ../clinical/instruments/SILICA-ASM-v1.yaml

Master Reference v1.0 §11.3, and `docs/IMPLEMENTATION_PLAN.md` §6 step 3.

**Why a generated migration rather than a loader run at deploy time.** An
instrument version is the thing every screening result points back at, so it
has to arrive the same way every other schema fact arrives: as a reviewed file
in the Alembic chain, applied once, in a known order, reversible. A loader
that ran on boot would make "which instrument does production hold?" a
question about process history rather than about the chain — and the answer
has to be reconstructable years later, when somebody asks which rules produced
a tier.

**The generated file is committed and reviewed like any other migration**, and
it is deliberately boring: it reads the YAML it was generated from, calls
`instrument_store.load()`, and commits. The clinical content stays in
`clinical/`, under the Clinical Lead's approval, rather than being copied into
a Python file where a later edit would diverge from the reviewed source
without anybody noticing.

**It refuses to generate from a file that is not approved.** A migration that
loads a draft would put an unapproved instrument into a database the moment
somebody ran `alembic upgrade head`, and `instrument_store.read_active()`
would then be one status edit away from classifying a real person against it.

Validate the file first — this script does not duplicate
`scripts/validate_instrument.py`, it refuses to proceed if that script would
fail.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from datetime import date
from pathlib import Path

import yaml

BACKEND = Path(__file__).resolve().parent.parent
REPO = BACKEND.parent
VERSIONS = BACKEND / "alembic" / "versions"

TEMPLATE = '''"""Load instrument {code} version {version}

Revision ID: {revision}
Revises: {down_revision}
Create Date: {today}

Data only. No schema change.

Master Reference v1.0 §8.3 and §11.3: "the migration that loads each version".
Generated by `scripts/gen_instrument_migration.py` from
`{source}`, which carries the Clinical Lead's
approval ({approved_by}, {approved_at}) on the pull request that added it
(§11.4).

The clinical content is **not** copied into this file. It is read from the
YAML at upgrade time, so the reviewed source and the loaded rows cannot
diverge — a Python copy of the cascade would be a second, unreviewed version
of the instrument, and the one thing §8.3 exists to prevent is two answers to
"which rules produced this tier?".

`instrument_store.load()` enforces what a schema cannot: `status: example` is
refused outright, and an already-stored `approved` or `retired` version is
immutable. Re-running this migration on a database that already holds
{code} v{version} therefore fails loudly rather than silently rewriting the
rules behind results that reference them.

The downgrade deletes the version and its rows. That is safe **only** while no
screening result references it; a result stamped with an instrument whose rows
are gone is uninterpretable, which is the failure §8.3 names. The downgrade
checks and refuses.
"""
from pathlib import Path
from typing import Sequence, Union

import yaml
from alembic import op
from sqlalchemy import text
from sqlalchemy.orm import Session

# revision identifiers, used by Alembic.
revision: str = {revision!r}
down_revision: Union[str, Sequence[str], None] = {down_revision!r}
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

#: Relative to the repository root, so this works from any working directory.
SOURCE = {source!r}
CODE = {code!r}
VERSION = {version}


def _document() -> dict:
    # backend/alembic/versions/<this file> -> repository root
    root = Path(__file__).resolve().parents[3]
    return yaml.safe_load((root / SOURCE).read_text(encoding="utf-8"))


def upgrade() -> None:
    """Insert the instrument version and all of its rows."""
    import sys

    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    from services import instrument_store

    session = Session(bind=op.get_bind())
    instrument_store.load(session, _document())
    session.flush()


def downgrade() -> None:
    """Remove the version, refusing while any result references it."""
    bind = op.get_bind()
    referencing = bind.execute(
        text(
            "SELECT COUNT(*) FROM screening_results "
            "WHERE instrument_code = :code AND instrument_version = :version"
        ),
        {{"code": CODE, "version": VERSION}},
    ).scalar()
    if referencing:
        raise RuntimeError(
            f"{{referencing}} screening result(s) reference {{CODE}} v{{VERSION}}. "
            "Removing the rules they were produced by would make those results "
            "uninterpretable (§8.3). Downgrade refused."
        )

    instrument_id = bind.execute(
        text("SELECT id FROM instruments WHERE code = :code AND version = :version"),
        {{"code": CODE, "version": VERSION}},
    ).scalar()
    if instrument_id is None:
        return

    for table in (
        "answer_options",
        "answer_bands",
        "instrument_channels",
        "scoring_rules",
    ):
        bind.execute(
            text(
                f"DELETE FROM {{table}} WHERE question_id IN "
                "(SELECT id FROM instrument_questions WHERE instrument_id = :id)"
            ),
            {{"id": instrument_id}},
        )
    for table in (
        "instrument_questions",
        "instrument_blocks",
        "instrument_conditions",
        "tier_rules",
        "safety_rules",
        "instrument_intervals",
    ):
        bind.execute(
            text(f"DELETE FROM {{table}} WHERE instrument_id = :id"), {{"id": instrument_id}}
        )
    bind.execute(text("DELETE FROM instruments WHERE id = :id"), {{"id": instrument_id}})
'''


def _current_head() -> str:
    """The revision this migration should follow, from Alembic itself rather
    than from a guess about filenames."""
    result = subprocess.run(
        [sys.executable, "-m", "alembic", "heads"],
        cwd=BACKEND,
        capture_output=True,
        text=True,
    )
    for line in result.stdout.splitlines():
        line = line.strip()
        if line and not line.startswith("INFO"):
            return line.split()[0].replace("(head)", "").strip()
    raise SystemExit(
        "Could not read the current Alembic head. Run `alembic heads` in "
        f"backend/ and look at the error:\n{result.stdout}\n{result.stderr}"
    )


def _next_number() -> str:
    existing = [
        path.name.split("_", 1)[0]
        for path in VERSIONS.glob("0*.py")
        if path.name[:4].isdigit()
    ]
    return f"{max((int(n) for n in existing), default=0) + 1:04d}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the data migration that loads one instrument version."
    )
    parser.add_argument("instrument", help="Path to clinical/instruments/<CODE>-v<n>.yaml")
    parser.add_argument(
        "--allow-unapproved",
        action="store_true",
        help=(
            "Generate from a draft. For rehearsing the mechanism only — a "
            "migration that loads an unapproved instrument must never reach a "
            "branch that can merge."
        ),
    )
    args = parser.parse_args(argv)

    source = Path(args.instrument).resolve()
    if not source.exists():
        print(f"No such file: {source}", file=sys.stderr)
        return 1

    validate = subprocess.run(
        [sys.executable, str(BACKEND / "scripts" / "validate_instrument.py"), str(source)],
        cwd=BACKEND,
        capture_output=True,
        text=True,
    )
    if validate.returncode != 0:
        print(validate.stdout + validate.stderr, file=sys.stderr)
        print(
            "The instrument does not validate, so no migration was generated. "
            "Fix it against clinical/instrument.schema.json first.",
            file=sys.stderr,
        )
        return 1

    doc = yaml.safe_load(source.read_text(encoding="utf-8"))
    status = doc.get("status")
    if status != "approved" and not args.allow_unapproved:
        print(
            f"{source.name} has status {status!r}. A migration that loads an "
            "unapproved instrument would put it into any database somebody "
            "upgrades, and read_active() would then be one status edit away "
            "from classifying a real person against it. Pass "
            "--allow-unapproved only to rehearse the mechanism.",
            file=sys.stderr,
        )
        return 1

    fixtures = source.with_suffix("").with_suffix(".fixtures.yaml")
    if not fixtures.exists():
        print(
            f"No fixtures beside it: expected {fixtures.name}. Every approved "
            "version ships with the answer profiles that pin its behaviour "
            "(§11.7), approved on the same pull request.",
            file=sys.stderr,
        )
        return 1

    code, version = doc["code"], int(doc["version"])
    number = _next_number()
    revision = f"{number}_load_{code.lower().replace('-', '_')}_v{version}"
    target = VERSIONS / f"{revision}.py"
    if target.exists():
        print(f"{target.name} already exists.", file=sys.stderr)
        return 1

    target.write_text(
        TEMPLATE.format(
            code=code,
            version=version,
            revision=revision,
            down_revision=_current_head(),
            today=date.today().isoformat(),
            source=source.relative_to(REPO).as_posix(),
            approved_by=doc.get("approved_by") or "not recorded",
            approved_at=doc.get("approved_at") or "not recorded",
        ),
        encoding="utf-8",
    )

    print(f"Wrote {target.relative_to(REPO).as_posix()}")
    print(
        "\nRead it before committing. Then:\n"
        "  ./venv/Scripts/python.exe -m alembic upgrade head\n"
        "  ./venv/Scripts/python.exe -m pytest tests/test_instrument_regression.py\n"
        "\nThe regression suite will pick the fixtures up automatically and "
        "stop using the synthetic example."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
